#!/usr/bin/env node
// Generates `apps/web/wrangler.dev.jsonc` from `apps/web/wrangler.jsonc` —
// byte-derived, never hand-maintained, so it cannot drift from the real
// bindings/vars `wrangler.jsonc` declares.
//
// The one thing it strips is the top-level `assets.run_worker_first` array.
// That setting is real, deliberate PRODUCTION behavior (Phase 2 of the
// app-subdomain migration, ADR-0010: it makes `src/worker.ts` run in front
// of the ASSETS binding for every document path, closing an app-host
// boundary gap) — but `astro dev`'s Cloudflare platform proxy reads this
// same top-level config to emulate Workers Assets routing locally, and with
// a bare `/*` pattern it also matches Vite's own internal dev-only requests
// (`/@vite/client`, `/@react-refresh`, component modules served from their
// raw absolute filesystem path, etc.). Those aren't real, listable assets,
// so they can't be named in an exclusion glob the way `!/_astro/*` can, and
// routing them into `src/worker.ts`'s fetch handler 404s them — silently
// breaking every `client:load`/`client:idle` island's hydration (found via
// PR #171's real CI: `setup-customer.setup.ts`'s "Create account" click
// never revealed the Display name field). `astro.config.mjs` points
// `configPath` at this generated file only for the `astro dev` command;
// `astro build` (and therefore `dist/server/wrangler.json`, the config
// `scripts/deploy.sh` actually deploys) always reads the real
// `apps/web/wrangler.jsonc` untouched.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parse as parseJsonc } from "jsonc-parser";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const sourcePath = `${repoRoot}apps/web/wrangler.jsonc`;
const outputPath = `${repoRoot}apps/web/wrangler.dev.jsonc`;

const source = readFileSync(sourcePath, "utf8");
const config = parseJsonc(source, [], { disallowComments: false, allowTrailingComma: true });

if (config.assets) delete config.assets.run_worker_first;

writeFileSync(
  outputPath,
  `// GENERATED by scripts/generate-dev-wrangler-config.mjs — do not edit by hand.\n// Source of truth is apps/web/wrangler.jsonc; re-run \`pnpm --filter @crawlpact/web dev\`\n// (or this script directly) after changing it.\n${JSON.stringify(config, null, 2)}\n`,
);
